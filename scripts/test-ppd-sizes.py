#!/usr/bin/env python3
"""Check the six HP-to-CUPS media-name normalizations through cupsfilter.

Usage:
  scripts/test-ppd-sizes.py HP_SOURCE.ppd[.gz] GENERATED.ppd [--fixture FILE]
                              [--filter PATH] [--keep DIR]

The source PPD is only read. cupsfilter writes raster files in a temporary directory;
no printer or CUPS queue is contacted. If the native filter is available, its emitted
DMPAPER is checked too.
"""

import argparse
import gzip
import importlib.util
import os
import shutil
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
FIXTURE = os.path.join(REPO, 'fixtures/inputs/text-1p.txt')
PAIRS = [
    ('8.5x13Custom', 'FanFoldGermanLegal', 258),
    ('B5JIS', 'B5', 13),
    ('16K195x270mm', '195x270mm', 264),
    ('16K184x260mm', '184x260mm', 263),
    ('16K197x273mm', '197x273mm', 257),
    ('Monarch', 'EnvMonarch', 37),
]


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, name + '.py'))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def ppd_bytes(path):
    with open(path, 'rb') as f:
        data = f.read()
    return gzip.decompress(data) if data.startswith(b'\x1f\x8b') else data


def ppd_text(path):
    return ppd_bytes(path).decode('latin1')


def check_inputs(source, generated):
    src = ppd_text(source)
    out = ppd_text(generated)
    if '*Manufacturer: "HP"' not in src or 'HP LaserJet Professional P1100' not in src:
        raise ValueError('source PPD does not identify itself as an HP LaserJet Professional P1100 PPD')
    if '*%% Generated by p1100-drivers scripts/make-ppd.py from an installed HP PPD.' not in out:
        raise ValueError('generated input lacks the make-ppd.py provenance marker')
    for old, new, _ in PAIRS:
        if not has_choice(src, old):
            raise ValueError('HP source PPD has no *PageSize choice %s' % old)
        if not has_choice(out, new):
            raise ValueError('generated PPD has no normalized *PageSize choice %s' % new)
        if has_choice(out, old):
            raise ValueError('generated PPD still has legacy *PageSize choice %s' % old)
        # Check the original choice records, including localized labels, byte for byte apart
        # from the choice identifier. Raster comparison alone cannot detect a changed label.
        for line in src.splitlines():
            head, sep, tail = line.partition(' ' + old + '/')
            if sep and head.lstrip('*').split('.')[-1] in (
                    'PageSize', 'PageRegion', 'ImageableArea', 'PaperDimension'):
                expected = head + ' ' + new + '/' + tail
                if expected not in out.splitlines():
                    raise ValueError('changed PPD choice record: ' + expected)

    # A source containing both names must fail before the generator produces duplicate keys.
    generator = load('make-ppd')
    collision = ppd_bytes(source) + b'\n*PageSize B5/Conflicting size: ""\n'
    try:
        generator.rewrite(collision, '/tmp/p1100-filter', '')
    except SystemExit as error:
        if 'both page-size choices' not in str(error):
            raise
    else:
        raise ValueError('generator accepted conflicting old and canonical page-size names')


def has_choice(ppd, name):
    return any(line.startswith('*PageSize ' + name + '/') for line in ppd.splitlines())


def raster_pages(data, cr):
    if len(data) < 4 or cr.u32(data, 0) != cr.SYNC_RASTER3:
        raise ValueError('cupsfilter output is not a RaS3 CUPS raster')
    pages = []
    pos = 4
    while pos < len(data):
        end_header = pos + cr.PAGE_HEADER_LEN
        if end_header > len(data):
            raise ValueError('truncated CUPS raster page header')
        header = cr.parse_header(data, pos)
        end = end_header + header['bytes_per_line'] * header['height']
        if end > len(data):
            raise ValueError('truncated raster pixels for page %d' % len(pages))
        pages.append((header, data[end_header:end]))
        pos = end
    if len(pages) != 1:
        raise ValueError('expected one raster page, got %d' % len(pages))
    return pages[0]


def cupsfilter(ppd, name, fixture, dst):
    cmd = [shutil.which('cupsfilter') or '/usr/sbin/cupsfilter', '-m',
           'application/vnd.cups-raster', '-p', ppd, '-o', 'PageSize=' + name, fixture]
    with open(dst, 'wb') as out:
        proc = subprocess.run(cmd, stdout=out, stderr=subprocess.PIPE)
    if proc.returncode:
        raise RuntimeError('cupsfilter failed for %s with %s:\n%s' %
                           (name, ppd, proc.stderr.decode('utf-8', 'replace')))


def check_media_code(filter_path, source_raster, generated_raster, expected, work, name, zc):
    env = dict(os.environ, P1100_NO_PJL='1')
    for label, raster in (('source', source_raster), ('generated', generated_raster)):
        job = os.path.join(work, 'job-' + label + '-' + name + '.zjs')
        with open(raster, 'rb') as src, open(job, 'wb') as dst:
            proc = subprocess.run([filter_path, '1', 'ppd-size-check', name, '1', ''],
                                  stdin=src, stdout=dst, stderr=subprocess.PIPE, env=env)
        if proc.returncode:
            raise RuntimeError('filter failed for %s PPD, %s:\n%s' %
                               (label, name, proc.stderr.decode('utf-8', 'replace')))
        _, stream, _ = zc.split_framing(open(job, 'rb').read())
        chunks = zc.parse_chunks(stream)
        values = [struct.unpack('>I', payload)[0]
                  for chunk in chunks if chunk['type'] == 2
                  for tag, kind, _, payload in chunk['items']
                  if tag == 3 and kind == zc.ITEM_TYPE_UINT32 and len(payload) == 4]
        if values != [expected]:
            raise ValueError('%s %s PPD emitted DMPAPER %r; expected %d' %
                             (name, label, values, expected))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('source', help='original HP PPD (.ppd or .ppd.gz)')
    ap.add_argument('generated', help='PPD generated by scripts/make-ppd.py')
    ap.add_argument('--fixture', default=FIXTURE, help='one-page input (default: repository fixture)')
    filter_args = ap.add_mutually_exclusive_group()
    filter_args.add_argument('--filter', dest='filter_path',
                             help='p1100-filter executable for DMPAPER checks')
    filter_args.add_argument('--no-filter', action='store_true',
                             help='skip the optional DMPAPER check')
    ap.add_argument('--keep', help='keep outputs under this existing directory')
    args = ap.parse_args(argv)

    cleanup = None
    try:
        check_inputs(args.source, args.generated)
        if not os.path.isfile(args.fixture):
            raise ValueError('fixture does not exist: ' + args.fixture)
        filter_path = None if args.no_filter else (args.filter_path or
                      os.path.join(REPO, 'target/release/p1100-filter'))
        if args.filter_path and not os.path.isfile(filter_path):
            raise ValueError('filter does not exist: ' + filter_path)
        if filter_path and not os.path.isfile(filter_path):
            filter_path = None
        if args.keep:
            if not os.path.isdir(args.keep):
                raise ValueError('--keep must name an existing directory')
            work = tempfile.mkdtemp(prefix='ppd-sizes-', dir=args.keep)
            cleanup = None
        else:
            cleanup = tempfile.TemporaryDirectory(prefix='p1100-ppd-sizes-')
            work = cleanup.name

        cr = load('cupsraster')
        zc = load('zjs-compare') if filter_path else None
        geometry = ('width', 'height', 'bits_per_color', 'bits_per_pixel', 'bytes_per_line',
                    'num_colors', 'resolution', 'margins', 'page_size', 'bbox', 'borderless')
        failures = 0
        for index, (old, new, code) in enumerate(PAIRS):
            source_raster = os.path.join(work, '%d-source.raster' % index)
            generated_raster = os.path.join(work, '%d-generated.raster' % index)
            cupsfilter(args.source, old, args.fixture, source_raster)
            cupsfilter(args.generated, new, args.fixture, generated_raster)
            try:
                src_header, src_pixels = raster_pages(open(source_raster, 'rb').read(), cr)
                out_header, out_pixels = raster_pages(open(generated_raster, 'rb').read(), cr)
                if src_header['page_size_name'] != old:
                    raise ValueError('%s raster reports page name %r' %
                                     (old, src_header['page_size_name']))
                if out_header['page_size_name'] != new:
                    raise ValueError('%s raster reports page name %r' %
                                     (new, out_header['page_size_name']))
                differences = [key for key in geometry if src_header[key] != out_header[key]]
                pixels_same = src_pixels == out_pixels
                if differences or not pixels_same:
                    raise ValueError('geometry differs: %s; pixel data %s' %
                                     (', '.join(differences) or 'none',
                                      'identical' if pixels_same else 'DIFFERENT'))
                if filter_path:
                    check_media_code(filter_path, source_raster, generated_raster, code,
                                     work, new, zc)
            except (ValueError, RuntimeError) as e:
                failures += 1
                print('%s -> %s: FAIL (%s)' % (old, new, e))
                continue
            report = '%dx%d, %d raster bytes identical' % (
                out_header['width'], out_header['height'], len(out_pixels))
            if filter_path:
                report += ', DMPAPER %d' % code
            print('%s -> %s: ok (%s)' % (old, new, report))

        if args.keep:
            print('outputs kept in ' + work)
        if failures:
            print('%d of %d media pairs differed' % (failures, len(PAIRS)), file=sys.stderr)
            return 1
        if not filter_path:
            print('DMPAPER check skipped (pass --filter PATH to enable)')
        print('all %d media pairs match' % len(PAIRS))
        return 0
    except (OSError, ValueError, RuntimeError) as e:
        print('error: ' + str(e), file=sys.stderr)
        return 1
    finally:
        if cleanup:
            cleanup.cleanup()


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
